# 농작업일정 재배법 본문이 그 꼴 그대로다. 머리글 한 줄 뒤에 자세한 줄이 붙는다.
#
#     씨뿌림                          ← 머리글
#     시 기 : 남부 2월 초순~2월 중순    ← 자세히
#     씨앗량 : 1㎗/10a
#     모 기르기                       ← 다음 머리글
#
# ⚠ 지어내지 않는다. 원문을 그대로 잇는다. 없으면 빈칸이다.

def _안내모으기(본문행들):
    """{작물: [(머리글, 자세한글)]}. 농작업일정 재배법에서만 모은다."""
    묶 = {}
    for r in 본문행들:
        if r.get("구분") != "재배법":
            continue
        작물 = 표준작물(r.get("작물"))
        if not 작물:
            continue
        글 = (r.get("본문") or "").strip()
        if not 글:
            continue
        칸 = 묶.setdefault(작물, [])
        # 머리글은 짧고 콜론이 없다. 자세한 줄은 '항목 : 값' 꼴이다
        머리인가 = ":" not in 글 and len(글) <= 14
        if 머리인가:
            칸.append([글, []])
        elif 칸:
            칸[-1][1].append(글)
    return 묶


# 줄글로 넘길 구분. 품종요약서·품종주요특성은 카탈로그라 뺀다 —
# 넣으면 6,616행이 재배법 1,231행을 덮어 검색이 카탈로그로 쏠린다
문서구분 = ("재배법", "기상재해대책", "생리적특성")

# 병합 후 이 길이 미만이면 버린다. 제목만 남은 껍데기다
최소길이 = 40


def crop_docs(본문행들):
    """
    mid_text 파편을 '작물 × 작형 × 구분 × 절' 로 묶어 문서 행으로 만든다.

    _안내찾기 와 나누는 이유:
        저쪽은 stage_name 에 맞는 덩이 **하나** 를 고른다(1:1). 짝이 없는
        머리글(관리·물주기·병해충 방제)은 버려진다.
        여기는 전부 넘긴다(1:N). 고를 일이 없으니 어휘 불일치 문제도 없다.

    자르지 않는 이유:
        청킹은 Safe-farm 의 app/knowledge/chunker.py 가 CHUNK_SIZE=480 토큰으로
        한다. 양쪽이 각자 자르면 경계가 갈려 같은 기준으로 비교할 수 없게 된다.
        그래서 5,663자짜리도 그대로 넘긴다 — `최대=400` 을 여기 두지 않는다.
    """
    묶 = {}
    for r in 본문행들:
        if r.get("구분") not in 문서구분:
            continue
        작물 = 표준작물(r.get("작물"))
        글 = (r.get("본문") or "").strip()
        if not 작물 or not 글:
            continue

        # 원문이 작물명에 작형을 섞어 둔다: '고추(보통재배)'
        원작물 = r.get("작물") or ""
        작형 = 원작물[원작물.find("(") + 1 : 원작물.rfind(")")] if "(" in 원작물 else ""

        키 = (작물, 작형, r["구분"], r.get("절", ""))
        칸 = 묶.setdefault(키, {"조각": [], "topic": "",
                               "file": r.get("출처파일", ""), "loc": r.get("위치", "")})

        # 머리글 판정은 _안내모으기 와 같은 규칙을 쓴다 — 두 벌로 두면 갈린다
        if not 칸["topic"] and ":" not in 글 and len(글) <= 14:
            칸["topic"] = 글
        else:
            칸["조각"].append(글)

    행들 = []
    for (작물, 작형, 구분, 절), v in 묶.items():
        body = " / ".join(v["조각"])
        if len(body) < 최소길이:
            continue
        행들.append({
            "crop_name": 작물,
            "cultivation_type": 작형,
            "section": 구분,
            "topic": v["topic"] or 절 or 구분,
            "body": body,
            "source_file": v["file"],
            "source_loc": v["loc"],
        })
    return 행들


# ★ 2026-09-19 — **원문 그대로는 화면에 거칠다.**
#   `guide_text` 는 밭 상세의 현재 단계 밑에 **그대로 출력된다**
#   (Safe-farm `StageTimeline.tsx`). 원문이 hwp 표에서 나온 글이라 —
#
#       시 기 : 남부 4월 하순~5월 상순, 중부 5월 상순~ 5월 중순
#       └ 낱말 사이 공백   └ 콜론 앞 공백      └ 물결 뒤 공백
#
#   실측(98행): 콜론 앞 공백 72 · 조합문자 8 · 쉼표 뒤 붙음 7 · 낱말 사이 공백 5
#               · 전각 콜론 4 · 물결 뒤 공백 4
#
# ⚠ **뜻은 건드리지 않는다.** 낱말을 바꾸거나 줄이지 않고 **띄어쓰기와 기호만** 고친다.
#   지어내지 않는다는 원칙(위 ⚠)은 그대로다.
# ⚠ `㎗ ㎥ ㎡ ㎏ ㏊ ℃` 는 **단위라 남긴다.** 풀어 쓰면 '리터'인지 '데시리터'인지
#   판단이 들어가고, 그 판단이 틀리면 씨앗량이 10배 어긋난다.
_거친공백 = re.compile(r"[ 	]{2,}")
_콜론앞 = re.compile(r"\s*[:：]\s*")
_물결뒤 = re.compile(r"~\s+")
_쉼표뒤 = re.compile(r",(?=[^\s])")
# '시 기' · '거 리' — 한 글자씩 떨어진 두 음절이 콜론 앞에 올 때만 붙인다.
# ⚠ 좁게 잡는다. 아무 데서나 공백을 지우면 '남부 4월' 이 '남부4월' 이 된다
# ⚠ 뒤돌아보기(`(?<!…)`)를 쓰면 **앞 글자가 통째로 사라진다** — 실제로 '시 기' 가
#   '기' 가 아니라 빈 문자열이 됐다(2026-09-19). 줄 맨 앞이나 ' / ' 뒤에서만 잡는다.
_낱말쪼개짐 = re.compile(r"(^|/ )([가-힣]) ([가-힣])(?=\s*[:：])")


def 안내다듬기(글):
    """화면에 그대로 나갈 글이라 **띄어쓰기와 기호만** 고른다. 뜻은 안 바꾼다."""
    if not 글:
        return 글
    글 = _낱말쪼개짐.sub(r"\1\2\3", 글)   # 시 기 → 시기
    글 = _콜론앞.sub(": ", 글)           # ' : ' · '：' → ': '
    글 = _물결뒤.sub("~", 글)            # '~ 5월' → '~5월'
    글 = _쉼표뒤.sub(", ", 글)           # '80cm(1줄),120cm' → ', 120cm'
    글 = _거친공백.sub(" ", 글)
    return 글.strip(" /").strip()


def _안내찾기(안내, 작물, 단계이름, 최대=400):
    """단계 이름에 맞는 머리글을 찾아 그 아래 줄들을 잇는다. 못 찾으면 빈 문자열."""
    후보 = 안내.get(작물) or []
    단순 = nospace(단계이름)
    for 머리, 줄들 in 후보:
        if not 줄들:
            continue
        ㅁ = nospace(머리)
        if ㅁ and (ㅁ in 단순 or 단순 in ㅁ):
            글 = 안내다듬기(" / ".join(줄들))
            return 글[:최대]
    return ""


