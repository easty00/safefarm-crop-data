# 작형 — 확정표 §A 에 없는 작물은 첨부 작형표에서 만든다
# ─────────────────────────────────────────────────────────────────────
# §A 는 사람이 손으로 적는 표라 16작물뿐이다. 전체 작물로 바뀌면서 그 표만으로는
# 나머지 140여 작물의 파종일·재배일수가 안 나온다. **자료에 있다** —
# 농작업일정 첨부의 작형표가 씨뿌림·아주심기·수확기를 순(旬)으로 적어둔다.
#
#     가지 | 촉성재배 | 씨뿌림 6.상~6.하 | 아주심기 8.하~9.상 | 수확 10.상~이듬해 6.하
#
# ⚠ **§A 가 있으면 §A 가 이긴다.** 확정표가 정본이라는 규칙 그대로다.
#   여기서 만든 줄은 §A 에 그 작물이 아예 없을 때만 쓴다.

_순쌍 = re.compile(r"(?:(\d{1,2})\s*월\s*)?([상중하])순?")


def _순들(글):
    """'12월 상순~1월 하순' → [(12,'상'), (1,'하')]. 달이 생략되면 앞의 달을 잇는다.

    ⚠ '2월 상~중순' 처럼 달을 한 번만 적는 꼴이 많다. 달을 기억해 두지 않으면
      뒤쪽 순이 통째로 빠져 재배일수가 짧게 나온다.
    """
    out, 달 = [], None
    for m in _순쌍.finditer(글 or ""):
        if m.group(1):
            달 = int(m.group(1))
        if 달 is None:
            continue
        out.append((달, m.group(2)))
    return out


def _시기(값):
    """`+MM-DD`(이듬해) 의 `+` 를 떼고 내보낸다. CSV 에는 `MM-DD` 만 나간다.

    ★ 2026-09-18 — **같은 상황을 두 가지로 적고 있었다.**

        덴드로비움  11-05 ~ +05-25    ← era_edge 가 13~24월을 '+' 로 적은 것
        셀러리     12-01 ~  02-28    ← 층이 달라 '+' 없이 그대로 넘어간 것

      둘 다 해를 넘는 파종 창인데 표기가 달랐다. 받는 쪽(Safe-farm)은 이 칸을
      `Text` 로 그대로 흘려보내므로, 언젠가 날짜로 파싱하면 '+' 쪽에서만 깨진다.

    ⚠ **'+' 를 떼도 잃는 것이 없다.** 끝이 시작보다 앞이면(`to < from`) 해를 넘는
      것이다 — 셀러리가 이미 그렇게 적혀 있고, 연도 없는 창이라 달리 읽을 수가 없다.

    ⚠ 안쪽(common.py `era_edge`·`middle_day`)의 '+' 는 그대로 둔다. 거기서는
      13~24월이 실제로 구분돼야 한다 — 떼는 것은 **CSV 로 나가는 자리에서만** 한다.
    """
    return (값 or "").lstrip("+")


def _표창(칸):
    """작형표 칸의 원문('2월 상순~5월 하순') → (시작, 끝). 못 읽으면 ('','').

    끝은 순의 **마지막 날**이다(`era_edge(last=True)`). 중앙일을 끝으로 쓰면
    하순에 심어도 되는 날이 창 밖으로 밀린다 — crop_variants 의 sow_to 와 같은 규칙.
    """
    것들 = _순들((칸 or "").strip())
    if not 것들:
        return "", ""
    return era_edge(*것들[0]), era_edge(*것들[-1], last=True)


def _창_작형표에서(작형표, 일정행들):
    """작형표(첨부)에서 **반대쪽 창**을 가져온다. 채운 칸 수를 돌려준다.

    ★ **§A 는 이 표에서 베낀 값이다.** 그래서 같은 쪽 창이 글자까지 맞는다 —
          §A 배추_봄  아주심기 4.상~5.중   ↔  표 '봄 재 배'  아주심기 4월 상순~5월 중순
      그 맞음을 열쇠로 써서 **어느 작형 줄인지** 집어내고, 비어 있는 쪽(씨뿌림
      3월 중순~4월 하순)을 가져온다. 작형 이름으로 맞추지 않는 까닭은 원문 띄어쓰기가
      제멋대로라서다('봄 재 배' · '봄재배' · '조 숙 재 배').

    ⚠ `crop_stages` 에서 채우는 것(`_창_단계에서`)보다 **이쪽이 먼저다.** 표는 작형별로
      씨·옮이 한 줄에 같이 있어 짝이 확실한데, 단계는 작형을 한 번 더 고른 뒤라
      변이와 다른 작형을 물어올 수 있다(배추가 그랬다).
    ⚠ 표에 없는 쪽은 그대로 빈다 — 시금치·마늘은 아주심기 칸이 '-' 다. 직파라서 맞다.
    """
    묶 = {}
    for r in 일정행들:
        씨, 옮 = (r.get("씨뿌림") or "").strip(), (r.get("아주심기") or "").strip()
        if not (씨 or 옮):
            continue
        작물 = 표준작물(r.get("작물"))
        if 작물:
            묶.setdefault(작물, []).append((_표창(씨), _표창(옮)))

    메움 = 0
    for a in 작형표:
        씨있, 옮있 = bool(a.get("씨시작")), bool(a.get("옮시작"))
        if (씨있 and 옮있) or not (씨있 or 옮있):
            continue
        내것 = a["씨시작"] if 씨있 else a["옮시작"]
        for (씨시작, 씨끝), (옮시작, 옮끝) in 묶.get(a.get("작물"), []):
            같은쪽 = 씨시작 if 씨있 else 옮시작
            반대쪽 = (옮시작, 옮끝) if 씨있 else (씨시작, 씨끝)
            if not 같은쪽 or not 반대쪽[0]:
                continue
            # 같은 쪽이 한 순(10일) 안에서 겹치면 그 줄이 이 작형이다
            차 = _상대일(같은쪽, 내것)
            if 차 == 999 or (차 > 같은작형허용 and (372 - 차) > 같은작형허용):
                continue
            if 씨있:
                a["옮시작"], a["옮끝"] = 반대쪽
            else:
                a["씨시작"], a["씨끝"] = 반대쪽
            메움 += 1
            break
    return 메움


def _창자리잡기(작형표):
    """§A 층의 **하나뿐인 창**이 씨 쪽인지 옮 쪽인지 정해 둔다.

    확정표 §A 는 사람이 손으로 적는 표라 `파종·정식` 칸이 하나다. `파종방법` 이
    '아주심기'·'모내기' 면 옮 쪽, 아니면 씨 쪽이다.

    ⚠ 반대쪽은 여기서 안 채운다. **`_창_단계에서` 가 crop_stages 를 보고 채운다** —
      거기는 작형이 이미 갈려 있어서(`_기간안`) 엉뚱한 작형의 날짜를 가져올 일이 없다.
      예전에 mid_schedule 을 직접 뒤졌다가 배추가 §A 봄재배 대신 겨울 작형을 물어 왔다.
    """
    for a in 작형표:
        if a.get("씨시작") or a.get("옮시작"):
            continue
        시작, 끝 = a.get("파종시작", ""), a.get("파종끝", "")
        if any(w in (a.get("파종방법") or "") for w in 옮낱말):
            a["옮시작"], a["옮끝"] = 시작, 끝
        else:
            a["씨시작"], a["씨끝"] = 시작, 끝


def _창_단계에서(변이들, 단계들):
    """`crop_stages` 의 날짜로 빈 창을 채운다. 채운 칸 수를 돌려준다.

    ★ **여기가 가장 믿을 만한 자리다.** `crop_stages` 는 이미 작형이 갈린 뒤라
      (`_기간안` 이 §A 의 파종일·일수로 걸러 냈다) 같은 작형의 씨·옮이 나란히 있다 —
          벼   1 모기르기 04-15~05-15  →  2 모내기때 05-15~06-15
          배추  1 씨뿌림 08-05~08-25    →  2 아주심기, 웃거름… 08-15~10-25
      원본을 다시 뒤지지 않고 이미 만든 것을 쓴다.

    ⚠ **있는 값을 덮지 않는다.** §A·작형표가 준 창이 이긴다 — 그쪽은 순(旬)의 양 끝이라
      창으로 더 정확하고, 단계 날짜는 중앙일이다.
    ⚠ 한 단계 이름에 씨·옮이 같이 있으면(배추 '아주심기, 웃거름, 김매기') **옮으로 본다.**
      단계 차례가 이미 씨 뒤라 뜻이 또렷하다 — `_씨옮창` 이 버리는 것과 다른 상황이다.
    """
    묶 = {}
    for r in 단계들:
        묶.setdefault((r["crop_name"], r["maturity_type"]), []).append(r)

    메움 = 0
    for v in 변이들:
        행 = 묶.get((v["crop_name"], v["maturity_type"]))
        if not 행:
            continue
        행 = sorted(행, key=lambda r: int(r["stage_order"]))
        씨 = 옮 = None
        for r in 행:
            이름 = r.get("stage_name") or ""
            if 옮 is None and any(w in 이름 for w in 옮낱말):
                옮 = r
            elif 씨 is None and any(w in 이름 for w in 씨낱말):
                씨 = r
        for r, 앞, 뒤 in ((씨, "seed_from", "seed_to"), (옮, "plant_from", "plant_to")):
            if not r or v.get(앞):
                continue
            시작 = (r.get("시작중앙일") or "").strip()
            if not 시작:
                continue
            # ⚠ **채운 뒤 씨→옮 간격이 말이 되는지 본다.** crop_variants 와 crop_stages 가
            #   서로 다른 작형을 고른 작물이 있다 — 배추는 변이가 봄(아주심기 4.상),
            #   단계가 가을(씨뿌림 8.상)이라 그대로 채우면 육묘가 239일이 된다.
            #   둘 중 무엇이 맞는지는 여기서 못 정한다. **말이 안 되면 안 채운다.**
            씨때 = _시기(시작) if 앞 == "seed_from" else v.get("seed_from", "")
            옮때 = _시기(시작) if 앞 == "plant_from" else v.get("plant_from", "")
            if 씨때 and 옮때:
                사이 = _상대일(옮때, 씨때)
                if 사이 == 999 or 사이 <= 0 or 사이 > 최대육묘일:
                    continue
            v[앞] = _시기(시작)
            v[뒤] = _시기((r.get("종료중앙일") or 시작).strip())
            메움 += 1
    return 메움


def _두창(작형):
    """작형 하나 → `seed_*` · `plant_*` 네 칸.

    ★ 왜 두 벌인가 — 등록 폼에 씨앗/모종 라디오가 있는데 안내 문구는 한 가지뿐이었다.
      씨앗을 고른 사람에게 모종 시기를 말하고 있었다(교안_파종시기_두벌 §1).

    세 층이 주는 것이 다르다.
        ②첨부 작형표 · ③일정 역산   씨·옮 창을 **각각** 담아 온다(`_씨옮창`)
        ①확정표 §A                 창이 하나뿐이다 — 사람이 손으로 적는 표라 칸이 없다.
                                   `파종방법` 으로 어느 쪽인지 갈라 한쪽에만 넣는다

    ⚠ 한쪽이 비는 것이 정상이다. 직파(감자·당근)는 `plant_*` 가 비고, 딸기·생강처럼
      씨로 안 심는 작물은 `seed_*` 가 빈다. **억지로 채우지 않는다.**
    """
    a = 작형 or {}
    # §A 의 한 창을 어느 쪽으로 볼지는 `_창메우기` 가 이미 정해 뒀다(main 에서 먼저 돈다)
    씨시작, 씨끝 = a.get("씨시작", ""), a.get("씨끝", "")
    옮시작, 옮끝 = a.get("옮시작", ""), a.get("옮끝", "")
    return {
        "seed_from": _시기(씨시작), "seed_to": _시기(씨끝),
        "plant_from": _시기(옮시작), "plant_to": _시기(옮끝),
    }


def _파종방법(작업명):
    """작업명에서 **방법 하나**만 뽑는다. `sow_method` 는 씨뿌림·아주심기 같은 한 낱말이다.

    ⚠ 원문 작업명이 세 가지로 지저분하다(2026-09-18) —
        '봄재배 씨뿌림'                    작형 접두가 붙는다
        '씨뿌림, 아주심기,뿌리꽂이, 분주'     여러 방법이 한 칸에 몰린다
        '발아기'                          방법이 아니라 생육단계다
      그래서 접두를 떼고, 앞의 것 하나만 쓰고, 방법말이 아니면 비운다.
    """
    이름 = re.sub(r"^(봄|가을|여름|겨울|1기작|2기작)\s*재배?\s*", "", (작업명 or "").strip())
    첫 = re.split(r"[,·/]", 이름)[0].strip()
    방법말 = ("씨뿌림", "씨뿌릴", "파종", "아주심기", "정식", "모기르기", "모 기르기", "육묘")
    for w in 방법말:
        if w in 첫:
            return w
    return ""                             # '발아기' 처럼 방법이 아닌 것은 비운다


# ★ 씨 뿌리는 일 · 옮겨 심는 일을 가르는 낱말 (2026-09-18)
#
#   `시작낱말` 과 따로 두는 까닭 — 저건 "이 작형이 언제 시작하나" 를 찾는 것이고,
#   이건 "같은 작형 안에서 씨와 모종이 각각 언제인가" 를 찾는 것이다. 벼가 그 차이다.
#       모기르기 4.중 → 모내기때 5.중        한 작형 안에 둘이 다 있다
씨낱말 = ("씨뿌림", "씨뿌릴", "파종", "모기르기", "모 기르기", "육묘", "묘대", "발아")
옮낱말 = ("아주심기", "정식", "모내기", "이앙", "옮겨")

# 씨 → 옮 사이가 이보다 길면 **뒷그루가 딸려 온 것**으로 본다.
#   사료용 보리(청보리)  파종 10.중 → 모내기 6.상
#   보리는 옮겨심지 않는다. 저 모내기는 보리를 걷고 그 논에 심는 **벼**다.
#   육묘가 가장 긴 고추가 60~70일이라 120일을 문턱으로 둔다.
최대육묘일 = 120

# §A 의 창과 일정의 창이 이보다 멀면 **다른 작형**으로 본다.
#   농작업일정은 순(旬) 단위라 중앙일이 최대 10일 어긋난다. 그 두 배를 준다.
같은작형허용 = 20


def _씨옮창(행들):
    """한 작형의 행에서 (씨 시작, 씨 끝, 옮 시작, 옮 끝) 을 뽑는다. 없으면 빈 문자열.

    ⚠ **한 작업명에 둘이 같이 있으면 버린다.** 3작물이 그렇다(2026-09-18) —
        두릅  "씨뿌림, 아주심기,뿌리꽂이"     ← 셋이 한 줄에
        고추  "발아기, 모기르기"              ← 씨 쪽이지만 뒤에 따로 '아주심기' 행이 있다
      자동으로 가르면 두릅이 "씨뿌림 3.상 → 아주심기 3.상" 이 되어 육묘 0일이 된다.
      한 줄에 둘 다 있으면 **어느 쪽인지 모르는 것**이므로 그 줄은 안 쓴다.

    ⚠ 씨가 옮보다 **뒤**면 짝이 아니다. 파일 차례가 작형 순서와 어긋난 것이거나
      뒷그루다. 그때는 옮만 남긴다 — 틀린 육묘 기간을 내놓는 것보다 낫다.
    """
    씨 = 옮 = None
    for r in 행들:
        이름 = (r.get("작업명") or "").strip()
        a = any(w in 이름 for w in 씨낱말)
        b = any(w in 이름 for w in 옮낱말)
        if a and b:
            continue                      # 한 줄에 둘 다. 가를 수 없다
        if a and 씨 is None:
            씨 = r
        elif b and 옮 is None:
            옮 = r
    def 창(r):
        if not r:
            return "", ""
        시작 = (r.get("시작중앙일") or "").strip()
        return 시작, (r.get("종료중앙일") or 시작 or "").strip()

    씨시작, 씨끝 = 창(씨)
    옮시작, 옮끝 = 창(옮)

    if 씨시작 and 옮시작:
        사이 = _상대일(옮시작, 씨시작)
        if 사이 == 999 or 사이 <= 0 or 사이 > 최대육묘일:
            씨시작 = 씨끝 = ""            # 짝이 아니다. 옮만 남긴다
    return 씨시작, 씨끝, 옮시작, 옮끝


# ★ 2026-09-19 — **작형 표시행의 꼴이 둘이다.**
#   오래 `▶` 만 보고 있었는데, 원문에는 대괄호로 적은 문서가 따로 있다.
#
#       ▶    '봄재배 ▶' · '고랭지재배(봄 씨뿌림) ▶'      133행 54작물
#       [ ]  '[ 식용 ]' · '[봄재배]' · '[직파재배]'        15행 6작물
#              감자 · 옥수수 · 들깨(잎) · 들깨(종실) · 유채 · 메밀
#
#   `[ ]` 를 못 알아보면 그 여섯은 **작형이 전부 한 줄기로 붙는다.** 옥수수가 그랬다 —
#   식용(7월 수확) · 곡실,사료용(9월 수확) · 찰옥수수 셋이 이어져 수확이 한가운데 오고,
#   `수확이_마지막인가` 에 걸려 세 숙기가 통째로 버려졌다(2026-09-19).
#
#   ⚠ 여는 대괄호로 **시작하는** 줄만 본다. '수확(2차)' 처럼 가운데 괄호가 든 작업명을
#     표시행으로 오인하면 진짜 단계가 사라진다.
_표시괄호 = re.compile(r"^\s*[\[［]")


# ★ 2026-09-19 — **작물별로 단계에서 빼는 행.**
#   원본이 한 줄기에 여러 차수를 섞어 놓아, 날짜로 세우면 수확이 한가운데 오는 것들이다.
#   `수확이_마지막인가` 에 걸려 작물이 통째로 버려지므로 **빼도 되는 행만 골라 뺀다.**
#
#   ⚠ 표시행(`▶`·`[ ]`)으로 갈리는 것은 여기 적지 않는다. 그건 _표시행인가 가 처리한다.
#   ⚠ 여기 적는 것은 **작업명이 정확히 같은 줄**이다. 부분일치가 아니다 —
#     '수확(2차)' 를 빼려다 '수확' 까지 빼면 그 작물이 통째로 사라진다.
#
#   적은 까닭을 한 줄씩 남긴다. 까닭을 못 적겠으면 빼지 말 것.
단계제외 = {
    # 2회 예취 사료작물이다. 1차 수확 → 재생 → 2차 수확으로 이어지는데
    # **한 재배 주기는 1차 수확까지**다. 재생기(08-05)가 수확(1차)(07-15) 뒤에 와서
    # 수확이 마지막이 아니게 된다.
    "수수,수단그라스 교잡종": ("재생기", "수확(2차)"),
    # 생육단계 줄기와 농작업 줄기가 한 표에 섞여 있다 —
    #     생육단계   발아,어린 모 시기(05-05) → 생육기(08-05)
    #     농작업     씨뿌림(04-25) → 아주심기(05-15) → 수확(07-25)
    # `생육기` 는 수확과 기간이 겹치는 두루뭉술한 칸이라 빼도 잃는 것이 없다.
    # 빼면 씨뿌림 → 발아 → 아주심기 → 수확 으로 제 차례가 선다.
    "컬리플라워(백색꽃양배추 고랭지재배)": ("생육기",),
    "파슬리(향미나리)": ("생육기",),
    # 문서에 작형이 셋이다 — [ 식용 ] · [ 곡실, 사료용 ] · [찰옥수수 노지재배].
    # 확정 작형은 **보통직파재배(식용)** 이고 7월에 풋옥수수로 딴다. `등숙기`(08-15)는
    # 곡실·사료용 작형의 단계인데 식용 작형의 기간(106일+여유) 안에 들어와,
    # `수확, 출하`(07-15) **뒤에** 붙어 세 숙기를 통째로 버리게 만들었다.
    #   ⚠ `직파, 육묘이식`(찰옥수수)은 `직파,육묘이식`(식용)과 **띄어쓰기만 다른 같은 말**이라
    #     같은 단계가 두 번 보인다. 공백을 접어 한 이름으로 보는 방법도 있으나, 그러면
    #     참깨의 `유묘 신장기`·`유묘신장기`가 한 단계로 합쳐져 **단계가 깎인다**(2026-09-19).
    #     좁게 여기서만 뺀다.
    "옥수수": ("등숙기", "직파, 육묘이식"),
    # 문서에 가을재배·봄 재배가 같이 실려 있는데 단계 이름이 거의 겹쳐, 중복을 걸러내면
    # **가을 한살이만 남는다**(10월 파종 → 월동 → 6월 수확). 그런데 봄에만 있는 이름
    # `파종 및 제초제 살포`(02-25) 하나가 남아 기준일을 봄으로 끌어당긴다 —
    # 기준이 봄이 되면 가을 파종·유묘기·로제트형 발달기가 수확 뒤로 밀려 통째로 버려진다.
    # 이 한 줄을 빼면 기준이 `파종, 제초제`(10-05)가 되어 제 차례가 선다.
    "유채": ("파종 및 제초제 살포",),
}


def _제외행인가(작물, 이름):
    """이 작물에서 단계로 세지 않기로 한 행인가. 작업명이 **정확히 같을 때만** 참."""
    return (이름 or "").strip() in 단계제외.get(작물, ())


def _표시행인가(이름):
    """작형을 가르는 표시행인가. 단계도 농작업도 아니므로 세지 않고 자리만 끊는다."""
    이름 = (이름 or "")
    return "▶" in 이름 or bool(_표시괄호.match(이름))


def _작형_일정(일정행들, 있는작물):
    """작형표조차 없는 작물 — **생육과정 일정 그 자체**에서 파종일·재배일수를 만든다.

    ⚠ 첨부 작형표는 38작물에만 있다. 그것만으로 끊으면 나머지 100여 작물이
      crop_stages 에서 통째로 빠진다 — 일정은 있는데 단계가 안 나오는 꼴이다.

    ⚠ 작형은 정보구분 꼬리에서 온다. 꼬리가 여럿이면 **행이 가장 많은 꼬리**를 쓴다.
      첫 꼬리를 쓰면 시설 작형이 대표가 되는 작물이 생긴다.
      꼬리가 없으면 작형을 비운다 — `_작형맞나` 가 꼬리 없는 행만 받게 된다.
    """
    묶 = {}
    for r in 일정행들:
        if not (r.get("정보구분") or "").startswith("생육과정"):
            continue
        작물 = 표준작물(r.get("작물"))
        if not 작물 or 작물 in 있는작물:
            continue
        # ⚠ 작형이 `정보구분` 꼬리에만 있는 문서와 `작형` 칸에만 있는 문서가 둘 다 있다.
        #   꼬리만 보면 피망이 샌다 — 꼬리가 없어 '기본' 이 되는데 `작형` 칸에는
        #   '촉성재배' 가 적혀 있다(2026-09-18). 둘 다 보고 있는 쪽을 쓴다.
        꼬리 = (r.get("정보구분") or "").split(" - ", 1)
        작형이름 = (꼬리[1].strip() if len(꼬리) > 1 else "") or (r.get("작형") or "").strip()
        묶.setdefault((작물, 작형이름), []).append(r)

    큰것 = {}
    for (작물, 작형), 행 in 묶.items():
        앞 = 큰것.get(작물)
        if 앞 is None or len(행) > len(앞[1]):
            큰것[작물] = (작형, 행)

    out = []
    for 작물, (작형, 행) in 큰것.items():
        # ⚠ **한 덩이 안에 작형이 여럿 들어 있다.** `작형` 칸도 정보구분 꼬리도 비었지만
        #   원문은 '봄(노지재배) ▶' 같은 표시행으로 갈라 두고, 같은 작업명을 작형 수만큼
        #   되풀이한다. 당근이 그랬다 —
        #       뿌리비대기 02-15 / 05-05 / 10-05 · 수확 05-05 / 10-25
        #   그대로 재면 파종 min(03-05) ~ 끝 max(11-25) = 268일이 되어
        #   "봄 파종 → 가을 수확" 이라는 없는 작형이 만들어진다(2026-09-18).
        #   crop_stages 가 쓰는 규칙을 그대로 쓴다 — **같은 작업명은 먼저 나온 것만.**
        #   그게 파일 차례상 첫 작형이다.
        # ⓐ ▶ 가 **작형 시작마다** 있으면 자리로 가른다. 2기작 작물이 그렇다 —
        #    멜론  봄재배 ▶ 12-25 파종 → 05-05 수확 · 여름재배 ▶ 05-15 파종 → 09-15 수확
        덩이, 현재 = [], []
        for r in 행:
            if _표시행인가(r.get("작업명")):
                if 현재:
                    덩이.append(현재)
                현재 = []
                continue
            현재.append(r)
        if 현재:
            덩이.append(현재)

        if len(덩이) >= 2:
            행 = 덩이[0]                   # ▶ 로 갈렸다. 첫 작형만 쓴다
        else:
            # ⓑ ▶ 가 맨 앞에 몰려 있어 자리로는 못 가른다(당근·양배추).
            #    대신 같은 작업명이 작형 수만큼 되풀이되므로 **먼저 나온 것만** 쓴다.
            본것, 첫작형 = set(), []
            for r in 행:
                이름 = (r.get("작업명") or "").strip()
                if _표시행인가(이름):
                    continue              # 작형 표시행. 단계가 아니다
                if 이름 in 본것:
                    continue              # 같은 작업명의 두 번째 = 다음 작형
                본것.add(이름)
                첫작형.append(r)
            행 = 첫작형 or 행

        시작들 = [r.get("시작중앙일") for r in 행
                 if any(w in (r.get("작업명") or "") for w in 시작낱말)
                 and r.get("시작중앙일")]
        날들 = [r.get("시작중앙일") for r in 행 if r.get("시작중앙일")]
        파종일 = min(시작들) if 시작들 else (min(날들) if 날들 else "")
        if not 파종일:
            continue

        # ⚠ **재배일수는 파종 → 그 다음 수확으로만 잰다.** 모든 행의 최댓값으로 재면
        #   부수 작업에 휘둘려 1년이 된다(2026-09-18에 겪은 것) —
        #     완두   '비닐등 자재준비' 11-15~12-25 가 **파종 전** 작업인데 파종일(01-05)
        #            기준 상대일로 접히며 −21일이 +354일이 됐다
        #     양배추  파일 차례가 봄·가을 뒤섞여 있어('수확 11-05' 가 '수확 06-05' 보다
        #            먼저 나온다) 가을 씨뿌림 + 봄 결구기가 한 작형이 됐다
        #   수확은 파종 뒤 **가장 가까운 것**을 쓴다. 그게 같은 작형의 수확이다.
        수확들 = [_상대일(r.get("종료중앙일") or r.get("시작중앙일"), 파종일) for r in 행
                 if any(w in (r.get("작업명") or "") for w in ("수확", "거두기", "수매"))]
        수확들 = [d for d in 수확들 if d != 999 and d > 0]
        if 수확들:
            끝들 = [min(수확들)]
        else:
            # 수확 행이 없는 작물(수수·잎을 계속 따는 산채 등). 남은 행으로 재되
            # ⚠ **파종 전 작업을 걸러낸다.** `_상대일` 은 음수를 +372 로 접으므로
            #   퇴비살포(04-25)가 파종(05-15)보다 앞서면 −20일이 **352일**이 된다.
            #   수수가 그래서 362일이었다. 노지 한살이 최장은 마늘 249일이니
            #   300 을 넘는 값은 파종 전 작업으로 본다.
            끝들 = [_상대일(r.get("종료중앙일") or r.get("시작중앙일"), 파종일) for r in 행]
            끝들 = [d for d in 끝들 if d != 999 and d <= 300]
        # ⚠ **파종 정보를 여기서도 채운다.** 예전에는 빈 문자열로 뒀는데, 그 탓에
        #   이 층(65작형)이 통째로 sow_method·sow_from·sow_to 를 못 냈다.
        #   파종일을 고른 그 행에 시작·종료 중앙일이 다 있으므로 같이 쓴다.
        #   작업명이 곧 방법이다 — '씨뿌림'·'아주심기'·'모기르기' 가 그대로 들어간다.
        심는행 = [r for r in 행
                 if any(w in (r.get("작업명") or "") for w in 시작낱말)
                 and (r.get("시작중앙일") or "") == 파종일]
        심기 = 심는행[0] if 심는행 else None
        씨시작, 씨끝, 옮시작, 옮끝 = _씨옮창(행)
        out.append({
            "작물": 작물, "작물키": f"{작물}_{작형 or '기본'}", "작형": 작형,
            "지역": "", "관측소": [],
            "파종일": 파종일,
            "파종방법": _파종방법(심기.get("작업명") if 심기 else ""),
            "파종시작": (심기.get("시작중앙일") or "") if 심기 else "",
            "파종끝": (심기.get("종료중앙일") or 심기.get("시작중앙일") or "") if 심기 else "",
            "씨시작": 씨시작, "씨끝": 씨끝, "옮시작": 옮시작, "옮끝": 옮끝,
            "일수": max(끝들) if 끝들 else "",
            "출처": "농작업일정 생육과정 일정에서 역산",
        })
    return out


def _작형_자료(일정행들, 있는작물):
    """첨부 작형표 행 → §A 와 같은 꼴. 확정표에 없는 작물만 만든다."""
    out, 본것 = [], set()
    for r in 일정행들:
        작물 = 표준작물(r.get("작물"))
        if not 작물 or 작물 in 있는작물:
            continue
        심기 = (r.get("씨뿌림") or "").strip() or (r.get("아주심기") or "").strip()
        거두기 = (r.get("수확기") or "").strip() or (r.get("성출하기") or "").strip()
        심기순, 거두기순 = _순들(심기), _순들(거두기)
        if not 심기순 or not 거두기순:
            continue
        작형 = re.sub(r"\s+", " ", (r.get("작형") or "").strip()) or "기본"
        키 = f"{작물}_{작형}"
        if 키 in 본것:
            continue                      # 같은 작형이 호마다 되풀이된다. 첫 줄만
        본것.add(키)
        파종일 = middle_day(*심기순[0])
        끝 = era_edge(*거두기순[-1], last=True)
        # ★ 이 층은 **표에 두 칸이 원래 따로 있다.** 예전에는 씨뿌림을 우선해 하나만 쓰고
        #   나머지를 버렸다 — 씨앗/모종을 따로 안내하려면 둘 다 있어야 한다(2026-09-18).
        씨순 = _순들((r.get("씨뿌림") or "").strip())
        옮순 = _순들((r.get("아주심기") or "").strip())
        out.append({
            "작물": 작물, "작물키": 키, "작형": 작형,
            "지역": "", "관측소": [],
            "파종일": 파종일,
            "파종방법": "씨뿌림" if (r.get("씨뿌림") or "").strip() else "아주심기",
            "파종시작": era_edge(*심기순[0]),
            "파종끝": era_edge(*심기순[-1], last=True),
            "씨시작": era_edge(*씨순[0]) if 씨순 else "",
            "씨끝": era_edge(*씨순[-1], last=True) if 씨순 else "",
            "옮시작": era_edge(*옮순[0]) if 옮순 else "",
            "옮끝": era_edge(*옮순[-1], last=True) if 옮순 else "",
            "일수": _사이일수(파종일, 끝),
            "출처": f"농작업일정 작형표 {r.get('출처파일', '')}",
        })
    return out

