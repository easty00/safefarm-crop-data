def 쪽별로(글):
    """PDF 는 쪽 표시가 들어 있다. [(쪽, 글토막)] 으로 나눈다. 없으면 통째로 한 덩이.

    쪽을 살려야 `위치` 에 쪽 번호를 적을 수 있다(CLAUDE.md 문서 파싱 절).
    """
    쪽, 덩이, 모음 = "", [], []
    for ln in (글 or "").split("\n"):
        m = 쪽표시.match(ln.strip())
        if m:
            if 덩이:
                모음.append((쪽, "\n".join(덩이)))
            쪽, 덩이 = m.group(1), []
            continue
        덩이.append(ln)
    if 덩이:
        모음.append((쪽, "\n".join(덩이)))
    return 모음 or [("", 글 or "")]


