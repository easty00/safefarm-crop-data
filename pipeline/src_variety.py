#   작물이 `svcCodeNm` 칸에 또박또박 적혀 있다. 본문을 훑을 이유가 없으므로
#   사전(CROP_ALIAS)을 곧바로 찾는다. 훑었다면 무·파가 조용히 빠졌을 것이다.
#
# 이 표는 품종정보에서만 쓰는 이름이라 여기 둔다.
# 다른 원본에도 '논벼' 가 나오면 crops.py 등록표의 '다른표기' 로 올릴 것.
이름보탬 = {"논벼": "벼"}


def 작물이름(*후보):
    """'논벼 > 일반벼' · 폴더이름 같은 것에서 표준 작물이름을 찾는다. 못 찾으면 ''."""
    for 후보하나 in 후보:
        for 조각 in re.split(r"[>＞]", 후보하나 or ""):
            키 = nospace(조각)
            if not 키:
                continue
            c = CROP_ALIAS.get(키) or 이름보탬.get(키)
            if c:
                return c
    return ""


