    시기모음 = {}

    for p in 원본파일들():
        # ⚠ 앞 4바이트만 읽는다. read_bytes() 는 파일을 통째로 올린다 —
        #   이 원본에는 31MB 짜리 첨부가 있어 형식 보자고 전부 읽으면 안 된다.
        with p.open("rb") as fh:
            형식 = 형식표.get(fh.read(4), "사진")
        if 형식 == "사진":
            샌것["사진"] += 1
            continue                      # 글자가 없는 게 맞다. 실패가 아니다
        글, 격자 = read_doc(p)
        if 형식 == "hwp3" and not tidy(글) and read_hwp3:
            글 = read_hwp3(p)             # ⚠ 위 주석 참고. read_any 가 못 읽는 갈래다
        if not tidy(글) and not 격자:
            샌것["빈글"] += 1
            continue

        # ⚠ 파일이름 앞 숫자가 cntntsNo 다. 655개 전부 이어지는 것을 확인했다.
        #   이 이음이 없으면 첨부에서 캔 값이 어느 품종 것인지 모른다.
        m = re.match(r"^(\d+)_", p.name)
        v = 번호별.get(m.group(1)) if m else None
        if v is None:
            샌것["번호못찾음"] += 1
        작물 = (v or {}).get("작물") or 작물이름(p.parent.name)
        if not 작물:
            continue
        if v is not None:
            v["첨부형식"] = 형식

        # ① 표 — hwpx·PDF 만 격자가 나온다. hwp 는 0개다(위 ⚠)
        for gi, g in enumerate(격자):
            for ri, row in enumerate(g):
                내용 = " ¦ ".join(tidy(c) for c in row)
                if not nospace(내용).strip("¦"):
                    continue
                table.append({"작물": 작물, "칸수": len(row), "내용": 내용[:600],
                              "출처파일": p.name, "위치": f"표{gi}/행{ri}"})

        # ② 본문 — 절 단위. 쪽 표시가 있으면 쪽까지 남긴다
        for 쪽, 토막 in 쪽별로(글):
            자리 = f"p{쪽}" if 쪽 else "본문"
            붙임 = {"작물": 작물, "구분": "품종요약서"}
            # ⚠ **깊이 3까지만 mid_text 로 보낸다.** hwp 387개는 표가 줄로 펴져 들어와
            #   맨살 줄(깊이 4)의 대부분이 표 찌꺼기다. 전부 담았더니 24개 파일에
            #   5,500행이 나왔다 — 655개면 15만 행이고, 그중 알맹이는 6%다.
            #   거른 줄은 texts.csv 에 원문 그대로 남는다. 그게 1층의 약속이다.
            for si, sec in enumerate(parse_sections(잔가지펴기(토막), 붙임)):
                본문 = tidy(sec.get("내용", ""))
                if 본문 and sec["깊이"] <= 3:
                    text.append({**sec, "본문": 본문[:1000],
                                 "출처파일": p.name, "위치": f"{자리}/{si}"})
            # ③ 온도 — 적산온도는 0건이다(확인함). 그래도 매번 부르는 까닭은
            #    "없다" 를 돌릴 때마다 다시 확인하기 위해서다. 자료가 늘면 여기서 잡힌다
            _t, _s = temp_from_sentence(토막, 작물, p.name, 자리)
            temp += _t
            sumt += _s

        # ④ 시기 — 표 · 머리블록 · 문장 셋 다
        for r in 시기캐기(글, 격자):
            if v is not None:
                시기모음.setdefault(v["cntntsNo"], {})[r["항목"]] = r
            text.append({"작물": 작물, "구분": "품종시기", "절": r["항목"],
                         "항목": (v or {}).get("품종명", ""), "깊이": 3,
                         "본문": f"{r['월']}.{r['일']} ({r['신뢰도']}) {r['원문']}"[:300],
                         "출처파일": p.name, "위치": "본문"})

        # ⑤ 숙기의 마지막 갈래 — 코드도 주요특성도 아무 말이 없는 품종만 본문에서 캔다
        #   ⚠ 주요특성이 '조중생' 이라고 말했으면 그건 이미 답이다. 여기서 덮으면 뒤엎는다.
        #     실제로 양파 '만추황' 이 주요특성에 조중생이라 적혀 있는데 본문의 딴 '조생' 에
        #     덮여 조생으로 들어갔다. 이름이 만추황인데 조생이다.
        if v is not None and not v["숙기"]:
            본문숙기, 원문, 갈래 = 숙기캐기(글)
            if 본문숙기:
                v["숙기"] = 본문숙기
                v["숙기가능성"] = 숙기가능성.get(본문숙기, "")
                v["숙기_본문"] = 본문숙기
                v["숙기근거"] = f"본문({갈래})" if 갈래 else "본문"
                v["숙기원문"] = v["숙기원문"] or 원문

    for v in 품종들:
        칸 = 시기모음.get(v["cntntsNo"], {})
        근거 = []
        for 이름 in 시기항목:
            r = 칸.get(이름)
            v[이름] = f"{r['월']}.{r['일']}" if r else ""
            if r:
                근거.append(f"{이름}:{r['신뢰도']}")
        # ★ 어떻게 찾았는지를 같이 남긴다. 숫자만 믿지 말고 원문을 보라는 뜻이다
        v["시기근거"] = " · ".join(근거)
    return temp, sumt, text, table, 샌것


