def 숙기캐기(글, 창=40):
    """글에서 숙기말 하나를 캔다.

    돌려주는 것 : (표준숙기, 원문토막, 갈래)
      갈래 ''        숙기말을 그대로 찾았다
           '복합'     '조중생' 이다. 낱말은 돌려주되 접을 때 가능성을 남긴다
           '풀어씀'    "숙기가 빠른" 을 조생으로 **해석했다**. 낱말을 본 게 아니다

    ⚠ **'못 찾았다' 와 '복합이라 못 정한다' 를 가른다.** 둘 다 숙기가 비지만 뜻이 다르다.
      복합인 품종에 뒤이어 첨부 본문에서 엉뚱한 숙기를 채우면 안 된다.
      실제로 양파 '만추황' 이 주요특성에 `조중생` 이라고 적혀 있는데도
      첨부 본문의 다른 '조생' 을 집어 **조생**으로 들어갔다. 이름이 만추황인데 조생이다.
    """
    글 = html.unescape(글 or "")
    for m in 복합숙기.finditer(글):
        가까이 = 글[max(0, m.start() - 숙기창):m.end() + 숙기창]
        if any(s in 가까이 for s in 숙기금지):
            continue
        # ⚠ 낱말을 '조중생' 하나로 모은다. 원문은 조중생·중조생·조중숙·조·중생 으로 갈린다
        return "조중생", tidy(글[max(0, m.start() - 20):m.end() + 30]), "복합"
    for m in 숙기말.finditer(글):
        가까이 = 글[max(0, m.start() - 숙기창):m.end() + 숙기창]
        if any(s in 가까이 for s in 숙기금지):
            continue                      # '조숙재배' 같은 작형·딴 뜻이다
        둘레 = 글[max(0, m.start() - 창):m.end() + 창]
        if 남의숙기.search(둘레):
            continue                      # 대비품종 것이다
        return 숙기표준.get(m.group(1), ""), tidy(둘레), ""
    # 낱말이 없으면 풀어 쓴 말을 본다. 배추·마늘이 이렇게 적는다
    for 패턴, 숙기 in 풀어쓴숙기:
        m = 패턴.search(글)
        if m:
            return 숙기, tidy(글[max(0, m.start() - 20):m.end() + 40]), "풀어씀"
    return "", "", ""


