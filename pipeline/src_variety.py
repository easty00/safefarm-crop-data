def 원본파일들():
    b = BASE / "첨부"
    return sorted(q for q in b.rglob("*") if q.is_file()) if b.exists() else []


def 계열(p):
    """첨부/<작물>/ 한 층이다. 재해예방정보처럼 두 층이 아니다."""
    b = BASE / "첨부"
    try:
        return p.relative_to(b).parts[0]
    except ValueError:
        return ""


def run():
    """raw + 첨부 를 읽어 중간 CSV 여섯 종으로.

    ⚠ 다른 src_*.py 의 run() 은 표 하나만 돌려준다. 이 원본만 품종 목록을 함께
      돌려준다 — varieties.csv 가 중간 CSV 여섯 종 밖이기 때문이다(위 ★).
      extract.py 는 run() 이 아니라 main() 을 부르므로 모양이 달라도 괜찮다.
    """
    품종들, 모름 = 품종목록()
    print(f"  품종 {len(품종들)}건 · 작물 이어진 것 {sum(1 for v in 품종들 if v['작물'])}건")
    if 모름:
        칸 = " · ".join(f"{k}×{v}" for k, v in sorted(모름.items(), key=lambda x: -x[1])[:6])
        print(f"  ⚠ sub_all.xml 에 없는 코드 {len(모름)}종 ({sum(모름.values())}건): {칸}")
        print("      대부분 grdlSeCode 의 332xxx 입니다. 코드만 남기고 이름은 비웁니다")

    temp, sumt, text2, table, 샌것 = 첨부읽기(품종들)
    temp, 버린온도 = 온도_거르기(temp)
    sumt, 버린적산 = 적산온도_거르기(sumt)
    if 버린온도 or 버린적산:
        print(f"  거른 것 — 생육 얘기가 아닌 온도 {버린온도}행"
              f" · '적산온도' 와 상관없는 숫자 {버린적산}행")
    표 = {
        "mid_schedule.csv": [],   # 순(旬) 단위 시기가 없다. 농작업일정에만 있다
        "mid_temp.csv": temp,
        "mid_sumtemp.csv": sumt,
        "mid_rule.csv": [],       # 재해 한계온도가 0건이다(맨 위 ⚠)
        "mid_text.csv": 주요특성_본문(품종들) + text2,
        "mid_table.csv": table,
    }
    return 표, 품종들, 샌것


