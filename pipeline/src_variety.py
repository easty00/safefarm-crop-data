# ⚠ `sections.py` 의 H3_RE 는 글머리표를 `- * ※ ·` 로만 본다. 그런데 품종요약서는
#   `⦁` `ㆍ` `가.` `①` `1)` 을 쓴다. 그대로 넘기면 **알맹이가 전부 깊이 4(맨살 줄)로
#   떨어져** 표 찌꺼기와 구분이 안 된다. 미리 `- ` 로 고쳐 깊이 3으로 들어가게 한다.
#
# ⚠ `[가-하]` 로 쓰면 한글 전체가 걸린다(U+AC00~U+D558). 글머리로 쓰이는 낱자만 적는다.
# ⚠ `\d{1,2}\s*\.` 은 넣지 않는다. **"7.24" 같은 출수기 날짜가 글머리로 둔갑한다.**
#   숫자는 `1)` 꼴만 받는다.
잔가지 = re.compile(
    r"^(\s*)(?:[⦁ㆍ․‧∙·•▪]|[가나다라마바사아자차카타파하]\s*[.)]|[①-⑳]|\d{1,2}\s*\))\s*")


def 잔가지펴기(토막):
    return "\n".join(잔가지.sub(r"\1- ", ln) for ln in (토막 or "").split("\n"))


