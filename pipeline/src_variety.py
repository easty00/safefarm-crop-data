def 날짜맞나(월, 일):
    """⚠ 표에는 날짜가 아닌 숫자가 함께 있다. 안 거르면 등숙률이 출수기가 된다.

        등숙률 92.3  ·  천립중 19.5  ·  쌀수량 543
        92.3 을 그냥 읽으면 92월 3일이 된다.
    """
    try:
        월, 일 = int(월), int(일)
    except (TypeError, ValueError):
        return False
    return 1 <= 월 <= 12 and 1 <= 일 <= 31


def 시기_표에서(격자):
    """hwpx·PDF 격자에서 머리글과 값을 짝짓는다. 자리가 확실해 가장 믿을 만하다."""
    out = []
    for 격 in 격자:
        if len(격) < 2:
            continue
        머리 = [nospace(c.replace("\n", " ")) for c in 격[0]]
        for ci, h in enumerate(머리):
            for 항목, 말들 in 시기항목.items():
                if not any(w in h for w in 말들):
                    continue
                # ★ 표의 첫 값 행이 그 요약서의 주인공 품종이다. 둘째 줄부터는 대비품종이다
                for row in 격[1:]:
                    if ci >= len(row):
                        continue
                    for ln in row[ci].split("\n"):
                        m = 날짜만.match(ln) or re.match(
                            r"^\s*(\d{1,2})\s*[.．]\s*(\d{1,2})", ln.strip())
                        if m and 날짜맞나(m.group(1), m.group(2)):
                            out.append({"항목": 항목, "월": int(m.group(1)),
                                        "일": int(m.group(2)), "신뢰도": "표",
                                        "원문": f"{h} = {' '.join(row[ci].split())[:40]}"})
                            break
                    break
    return out


def 시기_머리블록(줄들):
    """평문에서 '품종명' + '(월.일)' 머리 블록을 찾고 그 뒤 첫 날짜 줄을 값으로 본다."""
    for i, 줄 in enumerate(줄들):
        if not 머리시작.match(줄):
            continue
        블록 = 줄들[i:i + 30]
        if not any(단위표시.match(x) for x in 블록):
            continue                      # '(월.일)' 이 없으면 시기 표가 아니다
        차례, 끝 = [], i
        for j, x in enumerate(블록):
            for 항목, 말들 in 시기항목.items():
                if any(w in nospace(x) for w in 말들):
                    차례.append(항목)
            if 단위표시.match(x):
                끝 = i + j
        if not 차례:
            continue
        for x in 줄들[끝 + 1:끝 + 40]:
            m = 날짜만.match(x)
            if m and 날짜맞나(m.group(1), m.group(2)):
                둘레 = " | ".join(y.strip() for y in 줄들[max(0, 끝 - 2):끝 + 3])
                return [{"항목": 차례[0], "월": int(m.group(1)), "일": int(m.group(2)),
                         "신뢰도": "머리블록", "원문": 둘레[:90]}]
        break
    return []


