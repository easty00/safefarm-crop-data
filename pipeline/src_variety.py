# ⚠ `temp_from_sentence` 는 "한 줄에 '적산온도' 가 있고 ℃ 가 있으면" 적산온도로 본다.
#   이 원본에는 그 둘이 **한 줄에 있지만 서로 상관없는** 문장이 있다.
#
#     "출수 후 40일(’24), 적산온도 기준(’25), 치상 후 7일 조사 (포화습도 100%, 25℃)"
