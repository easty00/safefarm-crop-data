# `crops.difficulty` 를 §H 에 없는 작물까지 추정한다.
#
#     from difficulty import 추정표
#     표 = 추정표(OUT, 작물들)          # {작물: (난이도, 근거)}
#
# ★ 확정표 §H 에 사람이 적은 난이도는 22작물뿐이다. 나머지 100여 작물은
#   저쪽 밭등록 화면에서 난이도 칸이 빈 채로 그려진다. 그 22줄로 규칙을 만들어
#   나머지를 메운다 — **추정이므로 `difficulty_confirmed=N` 으로 나간다.**
#
# ★ 왜 이 축들인가 (2026-09-18 · 실패 일곱 번 뒤에 남은 것. 확정표 §H 참고)
#
#     작업 개수 · 글자수당 작업 밀도 · 시설 낱말 · 세 축 개수 세기 · 가중치 최적화
#     · 이용 부위 단독 · 부위+재배일수  — 전부 20~68% 에서 멈췄다.
#     밀도류가 특히 나빴다. 시금치 1.19 > 딸기 0.06 으로 **뒤집혔다** —
#     문서가 길면 밀도가 내려가니 결국 문서 분량을 잰 것이었다.
#
#   남은 둘은 문서 분량과 무관하다.
#
#     ① 이용 부위        parts.py. 열매를 먹는 과채는 유인·적심·열매솎기가 따른다
#     ② 병해충 발생 빈도  pest_alert.csv. 4년치(2023~2026) **실제 발생 경보**다.
#                       문서에 몇 번 적혔나가 아니라 몇 번 났나를 센다
#     ③ 방임재배 표기     방임(그냥 둠)이 **재배 방식의 하나로 표에 오르는** 작물.
#                       지금 자료에서 호박 하나다 — 농작업일정 수량표에 `방임재배 230`
#                       이라는 행이 있다. 나머지 작물에서 방임은 "방임재배보다는 유인하여"
#                       처럼 부정되는 쪽으로만 나온다
#
#   ①+② 로 22작물 중 19개(86%), ③ 을 더해 20개(91%) 가 맞는다.
#   틀리는 둘은 옥수수(38건)와 무(81건)다. 둘 다 발생은 잦은데 §H 는 쉬움이라 적었다 —
#   병이 나도 그냥 먹을 수 있는 작물이라는 뜻이고, 그 차이는 이 자료로는 못 가른다.
#
# ⚠ **저쪽에 넘어가는 것은 낱말뿐이다.** `쉬움·보통·어려움` — verify.py 난이도값 과
#   저쪽 ck_crops_difficulty 가 이 셋만 받는다. 등급을 늘리려면 세 곳을 같이 고친다.

import collections
import csv
import io
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import crops as C  # noqa: E402
import parts  # noqa: E402

쉬움, 보통, 어려움 = "쉬움", "보통", "어려움"

# 병해충 발생 빈도의 경계. 4년치 경보 1,464줄에서 센 값이다
잦음 = 5        # 이 아래면 "거의 안 난다"
매우잦음 = 140   # 벼(171)·복숭아(210) 가 여기 걸린다

# ⚠ 과수는 바닥이 보통이다. 다년생이라 전정·방제·적과가 해마다 돌아온다 —
#   경보에 안 잡혔다고 쉬움으로 내려가면 안 된다(감귤·체리처럼 0건인 과수가 9종 있다).
바닥있는부위 = {"과수": 보통}

# 방임재배를 **권하지 않는** 문장. 이것을 안 빼면 피망이 쉬움이 된다
#   "4본 유인재배 : 방임재배 대비 15% 증수" · "방임재배보다는 … 유인하여 재배"
방임아님 = re.compile(r"방임\s*재배\s*(?:보다|대비|하지|를\s*하지|→)|방임\s*수분")
방임 = re.compile(r"방임\s*재배")


def 병해충빈도(out: Path) -> dict:
    """{작물: 경보에 이름이 오른 줄 수}. pest_alert.csv 가 없으면 빈 표.

    ⚠ `대상작물` 칸만 보면 안 된다 — 절반이 비어 있고 작물은 `원문` 의
      "▶ (주의보) 해충 : 열대거세미나방 … (옥수수)" 꼴 안에 있다.
    ⚠ 이름 찾기는 `crops.crops_in_line` 에 맡긴다. 그냥 `in` 으로 세면
      '무' 가 "무름병"·"무렵" 에 걸려 402건이 된다(실제 81건).
    """
    경로 = out / "pest_alert.csv"
    센것 = collections.Counter()
    if not 경로.exists():
        return {}
    with io.open(경로, encoding="utf-8-sig", newline="") as fh:
        for r in csv.DictReader(fh):
            for 작물 in set(C.crops_in_line(r.get("원문") or "")):
                센것[작물] += 1
    return dict(센것)


def 방임작물(out: Path) -> set:
    """방임재배가 그 작물의 재배 방식 하나로 나오는 작물.

    ⚠ **부정되는 쪽이 더 많다.** 지금 자료에서 낱말은 4작물에 걸리는데 그중 셋
      (피망·늙은호박·단호박)이 "방임재배보다는 유인하여" · "방임재배 대비 15% 증수" 다.
      부정을 안 빼면 피망이 쉬움이 된다.

    ⚠ 호박도 "정지법 개선(방임재배→자만 3본)" 문장은 걸러지고, 수량표의 행 이름
      `방임재배 | 230 | …` 만 남는다. **권장이 아니라 "그렇게도 기른다" 는 표시**다.
      그것을 쉬움의 근거로 삼은 것은 사람의 판단이다(2026-09-18) — 호박은 수박과 달리
      물에도 크게 문제가 없고 방치해도 자라는 과채라는 것.

    직접 보려면 — `python feature/search_source.py 방임재배 --서비스 농작업일정`
    """
    나온것 = set()
    for 파일, 칸 in (("mid_text.csv", "본문"), ("mid_table.csv", "내용")):
        경로 = out / 파일
        if not 경로.exists():
            continue
        with io.open(경로, encoding="utf-8-sig", newline="") as fh:
            for r in csv.DictReader(fh):
                글 = 방임아님.sub("", r.get(칸) or "")
                if 방임.search(글) and (r.get("작물") or "").strip():
                    나온것.add(r["작물"].strip())
    return 나온것


def 추정(작물: str, 건수: int, 방임임: bool):
    """(난이도, 근거) 또는 (None, 까닭). 부위를 모르면 비운다."""
    부위 = parts.부위(작물)
    if not 부위:
        # 화훼·버섯·축산·약초. 노지 작물이 아니라 §H 의 잣대가 안 맞는다
        return None, "이용 부위 미상"
    if 방임임:
        return 쉬움, f"{부위}·방임재배 표기"

    if 부위 == "과채":
        값 = 어려움 if 건수 >= 잦음 else 보통
    elif 건수 >= 매우잦음:
        값 = 어려움
    elif 건수 >= 잦음:
        값 = 보통
    else:
        값 = 쉬움

    근거 = f"{부위}·병해충 {건수}건"
    바닥 = 바닥있는부위.get(부위)
    if 바닥 and 값 == 쉬움:
        return 바닥, 근거 + " (과수 바닥)"
    return 값, 근거


def 추정표(out: Path, 작물들) -> dict:
    """{작물: (난이도, 근거)}. 부위를 모르는 작물은 아예 안 담는다."""
    빈도 = 병해충빈도(out)
    방임들 = 방임작물(out)
    표 = {}
    for 작물 in 작물들:
        값, 근거 = 추정(작물, 빈도.get(작물, 0), 작물 in 방임들)
        if 값:
            표[작물] = (값, 근거)
    return 표


