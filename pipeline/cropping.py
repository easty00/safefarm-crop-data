import re

# 시설 작형을 가리키는 낱말. 공백을 지우고 본다 — 원문에 '촉 성 재 배' 가 있다
시설낱말 = ("촉성", "반촉성", "억제재배", "하우스", "시설", "가온", "겨울재배", "촉성재배")

# 한 작형이 이보다 길면 작형 여럿이 붙은 것으로 본다.
#   노지 한살이는 길어야 벼 137일 · 마늘 249일(확정표 §A 최장)이다.
#   250일을 넘는 것은 ②의 이어붙임이거나 다년생 과수다 — 둘 다 GDD 대상이 아니다.
최대일수 = 250

# 수확을 가리키는 낱말. '수확적기'·'조생종수확' 처럼 붙어 나온다
수확낱말 = ("수확", "거두기", "수매")


def _납작(s):
    return re.sub(r"\s", "", s or "")


def 시설인가(*글):
    """작형 이름·정보구분 꼬리 어디에든 시설 낱말이 있으면 참.

    ⚠ 여러 칸을 받는 이유: 작형이 `작형` 칸에만 있는 문서(피망)와
      `정보구분` 꼬리에만 있는 문서가 둘 다 있다. 한 칸만 보면 샌다.
    """
    flat = _납작(" ".join(x or "" for x in 글))
    return any(w in flat for w in 시설낱말)


def 너무긴가(일수):
    try:
        return int(float(일수)) >= 최대일수
    except (TypeError, ValueError):
        return False


def 거르기(작형들, 왜=None):
    """②③ 층 작형에서 시설·장기 작형을 뺀다. `왜` 를 주면 뺀 까닭을 세어 담는다."""
    남김 = []
    for a in 작형들:
        if 시설인가(a.get("작형"), a.get("작물키")):
            if 왜 is not None:
                왜["시설"] = 왜.get("시설", 0) + 1
            continue
        if 너무긴가(a.get("일수")):
            if 왜 is not None:
                왜["장기"] = 왜.get("장기", 0) + 1
            continue
        남김.append(a)
    return 남김


def 수확이_마지막인가(단계이름들):
    """단계 차례에서 수확이 맨 끝이면 참. 수확이 아예 없으면 참으로 본다.

    ⚠ 수확이 없는 작물이 있다 — 잎을 계속 따는 산채, 관상용. 그건 어긋남이 아니다.
      가려내려는 것은 **수확 뒤에 파종·육묘 단계가 오는** 꼴이다.
    """
    자리 = [i for i, n in enumerate(단계이름들) if any(w in (n or "") for w in 수확낱말)]
    if not 자리:
        return True
    return 자리[-1] == len(단계이름들) - 1
