import re

# 시설 작형을 가리키는 낱말. 공백을 지우고 본다 — 원문에 '촉 성 재 배' 가 있다
시설낱말 = ("촉성", "반촉성", "억제재배", "하우스", "시설", "가온", "겨울재배", "촉성재배")

# ★ **작형 이름이 없어 낱말로는 못 거르는 작물** (2026-09-18 추가)
#
#   낱말 거르기는 `작형` 칸을 읽는다. 그런데 농작업일정 첨부가 **한 장뿐인 작물은
#   작형 칸이 빈다** — 문서 안에서 작형을 나눌 까닭이 없으니 안 적은 것이다.
#   그러면 시설인가() 가 볼 글자가 아예 없어서 시설 문서가 그대로 통과한다.
#
#   ⚠ 본문에 시설 낱말이 있는지로 대신 볼 수는 없다. 노지 문서도 "비가림 재배"·
#     "시설의 현대화" 를 지나가듯 적는다(호박). 문서가 **통째로 시설 기준인지**는
#     사람이 읽어야 갈린다 — 그래서 표로 적고 까닭을 남긴다.
#
#   늘릴 때는 먼저 이렇게 확인한다 —
#       python feature/search_source.py 촉성 하우스 --작물 <작물> --서비스 농작업일정
시설작물 = {
    "멜론": "첨부가 촉성재배 안내서다 — '촉성재배시 기상이변에 대비한 보온시설 완비' ·"
          " '시설의 현대화 : 시설이 높고 환기 및 보온 시설완비'."
          " 12-25 파종은 노지 멜론이 아니다 (2026-09-18 확인)",
}

# 한 작형이 이보다 길면 작형 여럿이 붙은 것으로 본다.
#   노지 한살이는 길어야 벼 137일 · 마늘 249일(확정표 §A 최장)이다.
#   250일을 넘는 것은 ②의 이어붙임이거나 다년생 과수다 — 둘 다 GDD 대상이 아니다.
최대일수 = 250

# 월동작물은 가을에 심어 이듬해 초여름에 걷는다. 유채 263일 · 적채 273일이 정상이라
# 가을 파종에 한해 여기까지 인정한다(2026-09-18).
월동최대 = 290

# ─────────────────────────────────────────────────────────────────────
# 숙기별 재배일수 비율 — 2026-09-18 정함
#
# 조생·중생·만생을 나눠도 `days_to_harvest`·`gdd_target` 이 셋 다 같으면 나눈 뜻이 없다.
# 그런데 품종별 파종~수확 일수가 자료에 거의 없다(품종정보 수확기 4건 · 파종기 5건).
# 대신 **농진청 자료 두 건에서 얻은 비율**을 쓴다.
#
#     수박(착과 후)   소과+조생 36~39 / 중생 42 = 0.89   ·  만생 47 / 42 = 1.12
#     벼(출수 후)     조생 45~50 / 중생 50~55 = 0.90     ·  만생 55~60 / 52.5 = 1.10
#
# 둘이 0.9 / 1.1 로 모이므로 그 값을 쓴다. 국제적으로 통일된 공식은 없다 —
# 콩은 Maturity Group 00~13 숫자 체계, 감자는 작물별 절대 일수를 쓰고,
# "early/mid/late" 는 그 지역 생육기간에 **상대적으로** 부여된다(2026-09-18 확인).
#
# ⚠ 그러므로 이 비율로 만든 값은 전부 `confirmed=N` 이다. 품종별 실측이 들어오면 덮는다.
숙기비율 = {"EARLY": 0.9, "MID": 1.0, "LATE": 1.1}


def 숙기일수(일수, 숙기):
    """중생 기준 일수에 비율을 먹인다. 못 읽으면 그대로 돌려준다."""
    try:
        return round(int(float(일수)) * 숙기비율.get(숙기, 1.0))
    except (TypeError, ValueError):
        return 일수


# 수확을 가리키는 낱말. '수확적기'·'조생종수확' 처럼 붙어 나온다
수확낱말 = ("수확", "거두기", "수매")
# ⚠ 수확이 **아닌데** 수확 글자가 든 말. 체리의 `착과수확보`(착과·수확 확보)가
#   수확으로 잡혀 단계가 통째로 비었다(2026-09-18). 공백을 지우고 본다.
수확아님 = ("수확보", "수확확보", "수확예정", "수확기예상")


def _납작(s):
    return re.sub(r"\s", "", s or "")


def 시설인가(*글):
    """작형 이름·정보구분 꼬리 어디에든 시설 낱말이 있으면 참.

    ⚠ 여러 칸을 받는 이유: 작형이 `작형` 칸에만 있는 문서(피망)와
      `정보구분` 꼬리에만 있는 문서가 둘 다 있다. 한 칸만 보면 샌다.
    """
    flat = _납작(" ".join(x or "" for x in 글))
    return any(w in flat for w in 시설낱말)


# ★ **밭이 아닌 작형** (2026-09-18 추가)
#
#   세이프팜은 밭을 등록해 쓰는 서비스다. 같은 작물이라도 논에서 기르는 작형은
#   물 관리가 통째로 달라서 밭 기준 추천에 쓸 수 없다.
#
#   ⚠ 낱말 '논' 하나로 거르면 안 된다. 벼 작형은 '기계이앙'·'직파' 라 '논' 이 안 들어가고,
#     '콩(논재배)' 는 작형이 아니라 **작물 이름**이다 — 낱말로 거르면 엉뚱한 것이 걸리거나
#     정작 논 작형은 안 걸린다. 지금 자료에서 작형 이름에 논/밭 이 든 작물은 미나리뿐이라
#     작물·작형 **짝**으로 적는다.
#
#   보려면 — python feature/search_source.py 논미나리 --서비스 농작업일정
밭아닌작형 = {
    ("미나리", "논미나리재배"): "논미나리다. 우리가 쓰는 것은 밭미나리 —"
                            " 밭 등록이 전제인 서비스다 (2026-09-18 정함)",
}


def 밭아닌가(작물, 작형):
    """논 작형처럼 밭 기준 추천에 쓸 수 없는 작형인가."""
    return ((작물 or "").strip(), (작형 or "").strip()) in 밭아닌작형


def 시설작물인가(작물):
    """문서 전체가 시설 기준이라 작형 이름과 상관없이 빼는 작물인가.

    ⚠ 작물 **전체**를 빼는 것이라 낱말 거르기보다 세다. 표에 올리기 전에 원문을 읽는다.
    """
    return (작물 or "").strip() in 시설작물


def 너무긴가(일수, 파종일=None):
    """⚠ **월동작물은 250일을 넘는 것이 정상이다.**

        유채  10월 파종 → 이듬해 6월 수확   263일
        적채  8월 중순 파종 → 5월 중순 수확  273일   (작형표 '가을재배')

    그래서 가을(8~11월)에 심은 것은 290일까지 인정한다. 그보다 길면 작형이
    이어붙은 것이다 — 셀러리 366일이 그랬다. 파종일을 안 주면 옛 기준대로 잰다.
    """
    try:
        d = int(float(일수))
    except (TypeError, ValueError):
        return False
    if d < 최대일수:
        return False
    if 파종일 and str(파종일)[:2] in ("08", "09", "10", "11") and d <= 월동최대:
        return False
    return True


def 거르기(작형들, 왜=None):
    """②③ 층 작형에서 시설·장기 작형을 뺀다. `왜` 를 주면 뺀 까닭을 세어 담는다."""
    남김 = []
    for a in 작형들:
        if (시설인가(a.get("작형"), a.get("작물키"))
                or 시설작물인가(a.get("작물"))
                or 밭아닌가(a.get("작물"), a.get("작형"))):
            if 왜 is not None:
                왜["시설"] = 왜.get("시설", 0) + 1
            continue
        if 너무긴가(a.get("일수"), a.get("파종일")):
            if 왜 is not None:
                왜["장기"] = 왜.get("장기", 0) + 1
            continue
        남김.append(a)
    return 남김


def 수확이_마지막인가(단계이름들):
    """단계 차례에서 수확이 맨 끝이면 참. 수확이 아예 없으면 참으로 본다.

    ⚠ 수확이 없는 작물이 있다 — 잎을 계속 따는 산채, 관상용. 그건 어긋남이 아니다.
      가려내려는 것은 **수확 뒤에 파종·육묘 단계가 오는** 꼴이다.
    """
    자리 = [
        i for i, n in enumerate(단계이름들)
        if any(w in (n or "") for w in 수확낱말)
        and not any(w in _납작(n) for w in 수확아님)
    ]
    if not 자리:
        return True
    return 자리[-1] == len(단계이름들) - 1
