# 표준이름 전부.  ⚠ 거르는 데 쓰지 말 것 — 원본에 있는 것이 전부다
WANT, CROP_ALIAS, ALL_CROPS, CROP_STD, RAW_NAMES = _build_registry()

# 훑어 찾을 때 쓸 이름 차례. **긴 것부터** 본다.
# ⚠ 짧은 것을 먼저 찾으면 '강낭콩' 이 '콩' 으로, '중만생' 이 '중생' 으로 걸린다.
#   이 프로젝트가 숙기에서 이미 겪은 사고다 (CLAUDE.md 숙기말 함정).
SCAN_NAMES = sorted(CROP_ALIAS, key=len, reverse=True)

BRACKET = re.compile(r"[(（\[]\s*([^)）\]]{1,40})\s*[)）\]]")
SPLIT_DOT = re.compile(r"[·‧・,/]| 및 |과 |와 ")


def crops_in_line(line):
    """한 줄에서 작물을 찾는다. 못 찾으면 빈 집합.

    ⚠ 괄호 안을 먼저 본다. 이 문서들은 작물을 괄호로 묶어 적는다.
        • (마늘 ‧ 양파) 배수로 정비          ❍ (양파) 25℃ 이상의 고온에 생육 저하
      괄호 밖 이름은 **겹치지 않는 이름만** 받는다.
    """
    found = set()
    for m in BRACKET.finditer(line):
        for part in SPLIT_DOT.split(m.group(1)):
            c = CROP_ALIAS.get(nospace(part))
            if c:
                found.add(c)
    flat = nospace(line)
    # 절 제목은 괄호 대신 가운뎃점으로 잇는다 — "2 여름 배추 ‧ 무", "마늘·양파"
    # 겹치는 이름이라도 옆에 다른 작물이 붙어 있으면 작물로 본다
    for m in re.finditer(r"([가-힣]{1,6})\s*[·‧・]\s*([가-힣]{1,6})", line):
        a, b = CROP_ALIAS.get(nospace(m.group(1))), CROP_ALIAS.get(nospace(m.group(2)))
        if a and b:
            found.update((a, b))
    # ★ 긴 이름부터 찾고 걸린 자리는 지운다. '강낭콩' 을 찾은 자리에서 '콩' 을 또 찾지 않는다.
    남은 = flat
    for name in 가림이름:                  # 버린 문서의 이름 — 찾지 않고 자리만 지운다
        남은 = 남은.replace(name, "\x00" * len(name))
    for name in SCAN_NAMES:
        std = CROP_ALIAS[name]
        if name in AMBIGUOUS or std in AMBIGUOUS:
            continue                      # 괄호로만 인정
        if name not in 남은:
            continue
        bad = NOT_CROP.get(name) or NOT_CROP.get(std)
        if bad and not re.search(rf"{re.escape(name)}(?!{bad.pattern.split('(?=')[1][:-1]})", 남은):
            continue                      # 그 꼴로만 나왔다
        found.add(std)
        남은 = 남은.replace(name, "\x00" * len(name))
    return found


