def _lst_names():
    """lst_*.xml 전량 → {cntntsNo: (이름, 첨부파일명)}. **거르지 않는다.**

    ⚠ 예전에는 여기서 `if no not in WANT: continue` 로 걸렀다. 그 한 줄이
      160여 개 문서를 조용히 버리고 있었다. 지금은 있는 것을 다 담는다.
    """
    lst = RAW / "농작업일정" / "raw"
    if not lst.exists():
        return {}
    out = {}
    for p in sorted(lst.glob("lst_*.xml")):
        for it in ET.parse(p).getroot().findall(".//item"):
            no = (it.findtext("cntntsNo") or "").strip()
            이름 = (it.findtext("sj") or "").strip()
            파일 = (it.findtext("orginlFileNm") or it.findtext("fileName") or "").strip()
            if no:
                out[no] = (이름, 파일)
    return out


def _build_registry():
    """원본 전량 + 예외표 → 이름 사전. 손으로 두 번 적지 않는다."""
    raw = _lst_names()
    예외키 = {nospace(n) for 표준, 별, 문서 in CROPS
              for n in [표준, *별, *문서.values()]}
    alias, std = {}, {}

    def 잇기(이름, 표준):
        키 = nospace(이름)
        if not 키:
            return
        앞 = alias.get(키)
        if 앞 and 앞 != 표준:
            if 키 in 예외키:
                raise ValueError(f"작물 이름이 겹칩니다: {이름} → {앞} / {표준}")
            return                        # 원본 이름끼리면 먼저 잡은 쪽을 둔다
        alias[키] = 표준

    for 표준, 다른표기, 문서 in CROPS:
        for n in [표준, *다른표기, *문서.values()]:
            잇기(n, 표준)
        for no in 문서:
            std[no] = 표준

    # ★ 예외표에 없는 문서는 **제 이름이 곧 표준이름**이다
    for no, (이름, _파일) in raw.items():
        if no in 버릴문서:
            continue                      # ★ 작물로 만들지 않는다
        std.setdefault(no, 이름)
        잇기(이름, std[no])

    want = {no: (raw.get(no, ("", ""))[0] or std[no], std[no]) for no in std}
    return want, alias, set(std.values()), std, raw


# cntntsNo → (농작업일정 이름, 표준이름).  농작업일정 raw 를 고를 때 쓴다
